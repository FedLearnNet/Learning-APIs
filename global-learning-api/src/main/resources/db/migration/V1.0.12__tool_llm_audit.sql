create table tool_llm_audit (
    id bigint generated by default as identity,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    version bigint default 0 not null,
    keycloak_id varchar(255) not null,
    app_version_id bigint not null,
    status varchar(20) not null check (status in ('PENDING','RUNNING','FINISHED','FAILED')),
    commit_hash varchar(100),
    fingerprint varchar(64),
    verdict varchar(30) check (verdict in ('SAFE','SAFE_WITH_CONCERNS','UNSAFE','INCONCLUSIVE')),
    risk_level varchar(20) check (risk_level in ('CRITICAL','HIGH','MEDIUM','LOW','INFO')),
    report json,
    error_message TEXT,
    model_name varchar(255),
    source_available boolean not null default false,
    source_truncated boolean not null default false,
    reviewed_files integer not null default 0,
    total_files integer not null default 0,
    started_at timestamp(6),
    finished_at timestamp(6),
    primary key (id)
);

alter table if exists tool_llm_audit
    add constraint fk_tool_llm_audit_app_version
    foreign key (app_version_id) references federated_app_versions;

create index idx_tool_llm_audit_version on tool_llm_audit (app_version_id);
create index idx_tool_llm_audit_requester on tool_llm_audit (keycloak_id, created_at);
