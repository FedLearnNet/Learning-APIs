-- The execution model
create table execution_attempt (
    exit_code integer,
    progress real,
    trial_index integer not null,
    created_at timestamp(6) without time zone not null,
    finished_at timestamp(6) with time zone,
    id bigint generated by default as identity not null,
    last_log_message_id bigint,
    score_message_id bigint,
    started_at timestamp(6) with time zone,
    step_id bigint not null,
    updated_at timestamp(6) without time zone not null,
    version bigint not null default 0,
    public_id uuid not null,
    container_id character varying(255),
    status character varying(255) not null,
    failure jsonb,
    meta jsonb,
    params jsonb
);
create table execution_federation (
    relay_cert_attempts integer,
    relay_cert_signed boolean,
    relay_stopped boolean,
    start_aggregator boolean,
    created_at timestamp(6) without time zone not null,
    id bigint generated by default as identity not null,
    relay_cert_requested_at timestamp(6) with time zone,
    step_id bigint not null,
    updated_at timestamp(6) without time zone not null,
    version bigint not null default 0,
    relay_csr text,
    config jsonb
);
create table execution_file (
    attempt_id bigint not null,
    created_at timestamp(6) without time zone not null,
    file_id bigint not null,
    id bigint generated by default as identity not null,
    updated_at timestamp(6) without time zone not null,
    version bigint not null default 0,
    direction character varying(255) not null,
    name character varying(255) not null
);
create table execution_message (
    attempt_id bigint not null,
    created_at timestamp(6) without time zone not null,
    id bigint generated by default as identity not null,
    updated_at timestamp(6) without time zone not null,
    version bigint not null default 0,
    process character varying(255),
    type character varying(255) not null,
    message jsonb not null
);
create table execution_run (
    cohort_id bigint,
    connector_run_id bigint,
    created_at timestamp(6) without time zone not null,
    finished_at timestamp(6) with time zone,
    id bigint generated by default as identity not null,
    started_at timestamp(6) with time zone,
    updated_at timestamp(6) without time zone not null,
    version bigint not null default 0,
    public_id uuid not null,
    keycloak_id character varying(255),
    location character varying(255) not null,
    mode character varying(255) not null,
    name character varying(255),
    participant_id character varying(255),
    purpose character varying(255) not null,
    status character varying(255) not null,
    tool_type character varying(255),
    failure jsonb
);
create table execution_run_step (
    created_at timestamp(6) without time zone not null,
    finished_at timestamp(6) with time zone,
    global_app_version_id bigint,
    global_model_version_id bigint,
    id bigint generated by default as identity not null,
    run_id bigint not null,
    selected_attempt_id bigint,
    started_at timestamp(6) with time zone,
    transformer_id bigint,
    updated_at timestamp(6) without time zone not null,
    version bigint not null default 0,
    workflow_node_id bigint,
    public_id uuid not null,
    app_image character varying(255),
    app_name character varying(255),
    name character varying(255),
    status character varying(255) not null,
    failure jsonb,
    input_file_paths jsonb,
    inputs jsonb,
    search jsonb
);

