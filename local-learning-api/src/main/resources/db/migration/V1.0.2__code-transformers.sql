    create table code_transformers (
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        updated_at timestamp(6) not null,
        version bigint default 0 not null,
        code_hash varchar(64),
        mode varchar(255) not null check ((mode in ('ROW','CELL','PATIENT'))),
        name varchar(255) not null,
        status varchar(255) not null check ((status in ('BUILDING','READY','FAILED'))),
        image_name varchar(1000),
        body TEXT not null,
        description TEXT,
        data jsonb,
        files jsonb,
        goal jsonb,
        input_keys jsonb,
        return_keys jsonb,
        source_goals jsonb,
        primary key (id)
    );

    create table pipeline (
        code_transformer_id bigint not null,
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        updated_at timestamp(6) not null,
        version bigint default 0 not null,
        docker_tag varchar(64),
        container_id varchar(255),
        pipeline_status varchar(255) check ((pipeline_status in ('PENDING','RUNNING','SUCCESS','WARNING','STOPPED','FAILED'))),
        secret varchar(255),
        publish_info json,
        primary key (id)
    );

    create table pipeline_steps (
        progress integer,
        created_at timestamp(6) not null,
        finished_at timestamp(6),
        id bigint generated by default as identity,
        pipeline_id bigint not null,
        started_at timestamp(6),
        updated_at timestamp(6) not null,
        version bigint default 0 not null,
        error_code varchar(255),
        error_message TEXT,
        logs TEXT,
        name varchar(255) not null check ((name in ('PREFLIGHT','CLONE_REPO','BUILD_IMAGE','FETCH_CONFIG','FETCH_FILES','PUSH_IMAGE','SCAN_IMAGE','MALWARE_CHECK','RUN_PYTEST','COLLECT_SUMMARY'))),
        stepStatus varchar(255) not null check ((stepStatus in ('PENDING','RUNNING','SUCCESS','WARNING','STOPPED','FAILED'))),
        primary key (id)
    );

    alter table if exists pipeline
       add constraint fk_pipeline_code_transformer
       foreign key (code_transformer_id)
       references code_transformers;

    alter table if exists pipeline_steps
       add constraint fk_pipeline_steps_pipeline
       foreign key (pipeline_id)
       references pipeline;
